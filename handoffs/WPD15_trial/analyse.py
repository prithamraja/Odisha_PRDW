#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""WP-D15 T6: the trial tables, from the runner's JSON files in this folder.

    python handoffs/WPD15_trial/analyse.py

Reads current.json, sheet.json, sheet_choose.json, sheet_midsize.json and
sheet_no_insight.json; writes tables.md and review_items.json (every step 6
refusal and every step 7 log line, for judging by hand). No model call.
"""
import json
import statistics
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
BRIEF_18 = ["L01", "L04", "L06", "T02", "T04", "T14", "GEO-06", "GEO-07",
            "GEO-12", "GEO-18", "GEO-19", "GEO-20", "GEO-22", "GEO-24",
            "GEO-26", "GEO-29", "GEO-30", "GEO-32"]
TWO = ["TWO-01", "TWO-02", "TWO-03"]
ARMS = ["current", "sheet", "sheet_choose", "sheet_midsize"]


def load(label):
    path = HERE / f"{label}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def mid(values):
    values = [v for v in values if v is not None]
    return round(statistics.median(values), 1) if values else "-"


def pct(n, d):
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "-"


def main() -> int:
    runs = {a: load(a) for a in ARMS + ["sheet_no_insight"]}
    missing = [a for a in ARMS if runs[a] is None]
    if missing:
        print(f"missing runs: {missing}")
        return 1
    out = ["# WP-D15 trial tables", "",
           "Generated by `analyse.py` from the runner's JSON files in this "
           "folder. Writer calls only, on the held judge picks.", ""]

    # ── 1. per arm ───────────────────────────────────────────────────────────
    out += ["## 1. Per arm, all 21 place questions", "",
            "| | " + " | ".join(ARMS) + " |", "|---|" + "---|" * len(ARMS)]
    rows = {}
    for arm in ARMS:
        res = runs[arm]["results"]
        kept = [r for r in res if not r["lost"]]
        lost = [r for r in res if r["lost"]]
        m = [r["measures"] for r in kept if r.get("measures")]
        calls = sum(r["attempts"] for r in res)
        tok_in = sum(r["tokens"]["prompt"] for r in res)
        tok_out = sum(r["tokens"]["completion"] for r in res)
        wrong = sum(len(r.get("wrong_numbers_shown", [])) for r in res)
        notverb = sum(len(r.get("fallback_lines_not_verbatim", [])) for r in res)
        lost_on = Counter(k for r in lost for k in r["lost_on"])
        rows[arm] = {
            "Writer model": runs[arm]["writer_model"],
            "Runs per question": runs[arm].get("repeats", 1),
            "Answers": len(res),
            "Kept": pct(len(kept), len(res)),
            "Lost (both attempts refused)": len(lost),
            "Lost on": ", ".join(f"{k} {v}" for k, v in lost_on.items()) or "-",
            "Passed on the first try": pct(sum(1 for r in kept if r["attempts"] == 1), len(res)),
            "Wrong numbers shown (second pass)": wrong,
            "Fall-back lines not verbatim": notverb,
            "Writer calls": calls,
            "Seconds per answer, middle": mid(r["seconds"] for r in res),
            "Words, middle (kept)": mid(x["words"] for x in m),
            "Sentences, middle (kept)": mid(x["sentences"] for x in m),
            "Words per sentence, middle (kept)": mid(x["words_per_sentence"] for x in m),
            "Insights handed, middle": mid(r["findings"] for r in res),
            "Insights cited, middle (kept)": mid(x["findings_used"] for x in m),
            "Prompt tokens per call, middle": mid(
                c["prompt_tokens"] for r in res for c in r["checks"]
                if "prompt_tokens" in c) if arm != "current" else mid(
                r["tokens"]["prompt"] / max(1, r["attempts"]) for r in res),
            "Tokens in / out, all calls": f"{tok_in:,} / {tok_out:,}",
        }
    for name in rows["current"]:
        out.append(f"| {name} | " + " | ".join(str(rows[a][name]) for a in ARMS) + " |")
    out.append("")

    # ── 2. pass mark 2 ───────────────────────────────────────────────────────
    def lost_share(arm, ids):
        res = [r for r in runs[arm]["results"] if r["id"] in ids]
        return sum(1 for r in res if r["lost"]), len(res)

    cl, cn = lost_share("current", BRIEF_18)
    sl, sn = lost_share("sheet", BRIEF_18)
    limit = cl / cn + 1 / 18
    out += ["## 2. Pass mark 2: answers lost on the brief's 18 questions", "",
            "| Arm | Lost | Share |", "|---|---|---|",
            f"| current (1 run each) | {cl} of {cn} | {cl / cn:.1%} |",
            f"| sheet (3 runs each) | {sl} of {sn} | {sl / sn:.1%} |", "",
            f"Limit: current's share plus one answer in 18 = {limit:.1%}. "
            f"**{'HOLDS' if sl / sn <= limit + 1e-9 else 'FAILS'}**.", ""]
    for arm in ("sheet_choose", "sheet_midsize"):
        l, n = lost_share(arm, BRIEF_18)
        out.append(f"For reference, {arm}: {l} of {n} ({l / n:.1%}).")
    l, n = lost_share("sheet", TWO)
    out += [f"The three two-place questions, sheet arm: {l} of {n} lost.", ""]

    # ── 3. place facts used ──────────────────────────────────────────────────
    out += ["## 3. Place facts used (kept answers)", "",
            "| Arm | Kept | Lines used, middle (most) | Use A6 | Use a line with a standing | Use both |",
            "|---|---|---|---|---|---|"]
    for arm in ("sheet", "sheet_choose", "sheet_midsize"):
        kept = [r for r in runs[arm]["results"] if not r["lost"]]
        n = len(kept)
        used = [len(r["place"].get("lines_used", [])) for r in kept]
        out.append(
            f"| {arm} | {n} | {mid(used)} ({max(used, default=0)}) | "
            f"{pct(sum(r['uses_A6'] for r in kept), n)} | "
            f"{pct(sum(r['uses_standing_line'] for r in kept), n)} | "
            f"{pct(sum(r['uses_A6'] and r['uses_standing_line'] for r in kept), n)} |")
    out.append("")
    rows_used = Counter(row for r in runs["sheet"]["results"] if not r["lost"]
                        for row in r["lines_used_rows"])
    out += ["Rows cited across the kept `sheet` answers (a row counted once per "
            "line cited): " + ", ".join(f"{k} {v}" for k, v in rows_used.most_common()), ""]

    # ── 4. three-run agreement ───────────────────────────────────────────────
    for arm in ("sheet", "sheet_choose"):
        out += [f"## 4{'a' if arm == 'sheet' else 'b'}. How far three runs differ: {arm}", "",
                "Place facts used per question: in all three runs, in two, in one. "
                "A lost run counts as using the lines it showed on its fall-back "
                "(marked).", "",
                "| Question | Runs kept | In all 3 | In 2 | In 1 | Lines used per run |",
                "|---|---|---|---|---|---|"]
        tot = Counter()
        for qid in BRIEF_18 + TWO:
            res = sorted((r for r in runs[arm]["results"] if r["id"] == qid),
                         key=lambda r: r["run"])
            if not res:
                continue
            sets = [set(r["place"].get("lines_used", [])) for r in res]
            count = Counter(i for s in sets for i in s)
            k3 = sum(1 for v in count.values() if v == 3)
            k2 = sum(1 for v in count.values() if v == 2)
            k1 = sum(1 for v in count.values() if v == 1)
            tot.update({"3": k3, "2": k2, "1": k1})
            per = ", ".join(f"{len(s)}{'*' if r['lost'] else ''}" for s, r in zip(sets, res))
            out.append(f"| {qid} | {sum(not r['lost'] for r in res)} | {k3} | {k2} | {k1} | {per} |")
        total = sum(tot.values()) or 1
        out += ["", f"All questions: {tot['3']} lines in all three runs "
                f"({tot['3'] / total:.0%}), {tot['2']} in two ({tot['2'] / total:.0%}), "
                f"{tot['1']} in one ({tot['1'] / total:.0%}). `*` = a lost run.", ""]

    # ── 5. fall-backs ────────────────────────────────────────────────────────
    out += ["## 5. Fall-backs: how many place facts they showed", "",
            "| Arm | Fall-backs | Place facts shown: most | middle | Of them A1-A7 only (writer cited none) |",
            "|---|---|---|---|---|"]
    for arm in ("sheet", "sheet_choose", "sheet_midsize"):
        lost = [r for r in runs[arm]["results"] if r["lost"]]
        n = [len(r["place"].get("lines_used", [])) for r in lost]
        a17 = sum(1 for r in lost if all(row in ("A1", "A2", "A3", "A4", "A5", "A6", "A7")
                                         for row in r["lines_used_rows"])
                  and len(r["lines_used_rows"]) >= 5)
        out.append(f"| {arm} | {len(lost)} | {max(n, default='-')} | {mid(n)} | {a17} |")
    out.append("")

    # ── 6. two by-year series ────────────────────────────────────────────────
    out += ["## 6. Answers that cite a by-year sheet line AND a month-cube insight", ""]
    flagged = [(arm, r) for arm in ARMS for r in runs[arm]["results"]
               if r.get("two_year_series")]
    out.append(f"{len(flagged)} answer(s) flagged by code; each is read in the report.")
    for arm, r in flagged:
        out.append(f"- {arm} {r['id']} run {r.get('run', 1)}")
    out.append("")

    # ── 7. time and tokens ───────────────────────────────────────────────────
    def per_call(arm, key):
        return [c[key] for r in runs[arm]["results"] for c in r["checks"] if key in c]

    out += ["## 7. Writer time and tokens, current against sheet (the brief's 18)", "",
            "| | current | sheet |", "|---|---|---|"]
    for name, f in (("Seconds per answer, middle",
                     lambda a: mid(r["seconds"] for r in runs[a]["results"] if r["id"] in BRIEF_18)),
                    ("Seconds per writer call, middle",
                     lambda a: mid(c["seconds"] for r in runs[a]["results"] if r["id"] in BRIEF_18
                                   for c in r["checks"])),
                    ("Writer calls per answer, mean",
                     lambda a: round(statistics.mean(r["attempts"] for r in runs[a]["results"]
                                                     if r["id"] in BRIEF_18), 2)),
                    ("Prompt tokens per answer, middle",
                     lambda a: mid(r["tokens"]["prompt"] for r in runs[a]["results"] if r["id"] in BRIEF_18)),
                    ("Completion tokens per answer, middle",
                     lambda a: mid(r["tokens"]["completion"] for r in runs[a]["results"] if r["id"] in BRIEF_18))):
        out.append(f"| {name} | {f('current')} | {f('sheet')} |")
    out.append("")

    # ── 8. spend ─────────────────────────────────────────────────────────────
    out += ["## 8. Every model call", "", "| Run | Model | Calls | Tokens in | Tokens out | Cost |",
            "|---|---|---|---|---|---|"]
    for arm in ARMS + ["sheet_no_insight"]:
        if runs[arm] is None:
            continue
        for model, row in runs[arm]["spend"]["by_model"].items():
            cost = f"${row['usd']:.2f}" if row.get("usd") is not None else "price not set"
            out.append(f"| {arm} | {model} | {row['calls']} | {row['prompt_tokens']:,} | "
                       f"{row['completion_tokens']:,} | {cost} |")
    out.append("")

    # ── review items: step 6 refusals and step 7 lines ───────────────────────
    items = {"step6": [], "step7": []}
    for arm in ARMS:
        for r in runs[arm]["results"]:
            for c in r["checks"]:
                for f in c.get("standing_failures", []):
                    items["step6"].append({"arm": arm, "id": r["id"], "run": r.get("run", 1),
                                           "attempt": c["attempt"], "counts": c.get("standing_counts"),
                                           **f})
            for s in r.get("number_words_shown", []):
                items["step7"].append({"arm": arm, "id": r["id"], "run": r.get("run", 1), **s})
    (HERE / "review_items.json").write_text(json.dumps(items, ensure_ascii=False, indent=1),
                                            encoding="utf-8")
    out += [f"Step 6 refusals recorded: {len(items['step6'])}; step 7 log lines: "
            f"{len(items['step7'])} (both judged by hand in the report; listed in "
            f"review_items.json).", ""]
    (HERE / "tables.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
