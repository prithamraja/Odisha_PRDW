#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""WP-D15c T5: the live-check tables, from rule_on.json and rule_off.json here.

    python handoffs/WPD15c_trial/analyse.py

Writes tables.md and review_items.json. No model call.
"""
import json
import re
import statistics
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARMS = ["rule_on", "rule_off"]


def load(arm):
    return json.loads((HERE / f"{arm}.json").read_text(encoding="utf-8"))


def mid(values):
    values = [v for v in values if v is not None]
    return round(statistics.median(values), 1) if values else "-"


def block(results):
    kept = [r for r in results if not r["lost"]]
    lost = [r for r in results if r["lost"]]
    m = [r["measures"] for r in kept if r.get("measures")]
    handed = [r for r in kept if r["findings"]]
    return {
        "Answers": len(results),
        "Kept": len(kept),
        "Lost": len(lost),
        "Lost on": ", ".join(f"{k} {v}" for k, v in
                             Counter(k for r in lost for k in r["lost_on"]).items()) or "-",
        "Passed on the first try": sum(1 for r in kept if r["attempts"] == 1),
        "Wrong numbers shown (second pass)": sum(len(r["wrong_numbers_shown"]) for r in results),
        "Seconds per answer, middle": mid(r["seconds"] for r in results),
        "Words, middle (kept)": mid(x["words"] for x in m),
        "Sentences, middle (kept)": mid(x["sentences"] for x in m),
        "Insights handed, middle": mid(r["findings"] for r in results),
        "Insights cited, middle (kept)": mid(r["insights_cited"] for r in kept),
        "Kept answers citing fewer than half the insights handed":
            sum(1 for r in handed if r["insights_cited"] * 2 < r["findings"]),
        "Kept answers citing none of the insights handed":
            sum(1 for r in handed if r["insights_cited"] == 0),
    }


def main():
    runs = {a: load(a) for a in ARMS}
    out = ["# WP-D15c live check — tables", "",
           "Generated by `analyse.py`. Writer `gpt-6.2-sol`, the 50 held "
           "questions that reach the writer, once each per arm, through "
           "`Assembler.answer` (`run_writer_trial.py --sheets`).", ""]
    for split, pick in (("all 50", lambda r: True),
                        ("place answers", lambda r: r["names_a_place"]),
                        ("no-place answers", lambda r: not r["names_a_place"])):
        tables = {a: block([r for r in runs[a]["results"] if pick(r)]) for a in ARMS}
        out += [f"## Per arm — {split}", "", "| | rule_on (block) | rule_off (log, shipped) |",
                "|---|---|---|"]
        for name in tables["rule_on"]:
            out.append(f"| {name} | {tables['rule_on'][name]} | {tables['rule_off'][name]} |")
        out.append("")

    # pass mark 2
    lost = {a: sum(r["lost"] for r in runs[a]["results"]) for a in ARMS}
    out += [f"**Pass mark 2:** rule_off lost {lost['rule_off']}, rule_on lost "
            f"{lost['rule_on']} — **{'HOLDS' if lost['rule_off'] <= lost['rule_on'] else 'FAILS'}**.", ""]

    # pass mark 4
    more_than = [r["id"] for r in runs["rule_off"]["results"]
                 if r["names_a_place"] and "More than" in (r["shown_text"] or "")]
    level_words = re.compile(r"\b(GP|G\.P\.|Gram Panchayat|panchayat|block|district)\b", re.I)
    wrong_note = []
    for r in runs["rule_off"]["results"]:
        note = (r.get("place") or {}).get("note", "")
        if not note:
            continue
        for a in r["place"]["answered"]:
            # the officer wrote the level next to the name, yet a note names it
            pat = re.compile(r"\b" + re.escape(a["name"]) + r"\s+(GP|G\.P\.|Gram Panchayat|panchayat|block)\b"
                             r"|\b(GP|Gram Panchayat|panchayat)(\s+of)?\s+" + re.escape(a["name"]) + r"\b", re.I)
            if pat.search(r["question"]) and a["label"] in note.split(".")[0]:
                wrong_note.append((r["id"], r["question"], note))
    notes = [(r["id"], r["question"], r["place"]["note"]) for r in runs["rule_off"]["results"]
             if (r.get("place") or {}).get("note")]
    out += [f"**Pass mark 4:** rule_off place answers carrying the \"More than\" line: "
            f"{len(more_than)} {more_than or ''}; notes where the officer named the level: "
            f"{len(wrong_note)}. Notes printed: {len(notes)} — "
            + "; ".join(f"{i} ({q!r})" for i, q, _ in notes), ""]

    # cards / charts against the twin
    on = {r["id"]: r for r in runs["rule_on"]["results"]}
    fewer = []
    for r in runs["rule_off"]["results"]:
        t = on.get(r["id"])
        if not t:
            continue
        a, b = r["layout_counts"], t["layout_counts"]
        if a["cards"] < b["cards"] or a["panels"] < b["panels"]:
            fewer.append((r["id"], f"cards {a['cards']} vs {b['cards']}, charts {a['panels']} vs {b['panels']}"))
    out += [f"## Cards and charts", "",
            f"rule_off answers with fewer cards or charts than their rule_on twin: "
            f"**{len(fewer)}** of {len(runs['rule_off']['results'])}.", ""]
    out += [f"- {i}: {d}" for i, d in fewer] + [""]

    # zero-cited answers in full
    zero = [r for r in runs["rule_off"]["results"]
            if not r["lost"] and r["findings"] and r["insights_cited"] == 0]
    out += ["## rule_off answers handed insights that cite none of them", ""]
    for r in zero:
        out += [f"### {r['id']} — {r['question']} ({r['findings']} insights handed)", "",
                "```", r["shown_text"], "```", ""]
    if not zero:
        out += ["None.", ""]

    # spend
    out += ["## Model calls", "", "| Arm | Model | Calls | Tokens in | Tokens out | Cost |",
            "|---|---|---|---|---|---|"]
    for a in ARMS:
        for model, row in runs[a]["spend"]["by_model"].items():
            cost = f"${row['usd']:.2f}" if row.get("usd") is not None else "price not set"
            out.append(f"| {a} | {model} | {row['calls']} | {row['prompt_tokens']:,} | "
                       f"{row['completion_tokens']:,} | {cost} |")
    out.append("")

    items = {"step6": [], "step7": []}
    for a in ARMS:
        for r in runs[a]["results"]:
            for c in r["checks"]:
                for f in c.get("standing_failures", []):
                    items["step6"].append({"arm": a, "id": r["id"], "attempt": c["attempt"], **f})
            for s in r.get("number_words_shown", []):
                items["step7"].append({"arm": a, "id": r["id"], **s})
    (HERE / "review_items.json").write_text(json.dumps(items, ensure_ascii=False, indent=1),
                                            encoding="utf-8")
    out += [f"Step 6 log lines: {len(items['step6'])}; step 7 log lines: {len(items['step7'])} "
            f"(judged in the report; listed in review_items.json).", ""]
    (HERE / "tables.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    sys.exit(main())
